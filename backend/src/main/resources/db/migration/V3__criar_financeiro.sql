CREATE TABLE pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id UUID NOT NULL UNIQUE REFERENCES ordens_servico(id),
    valor_total NUMERIC(10,2) NOT NULL,
    valor_sinal_pago NUMERIC(10,2) NOT NULL,
    valor_pago NUMERIC(10,2) NOT NULL,
    saldo_devedor NUMERIC(10,2) NOT NULL,
    data_pagamento_sinal DATE,
    status_financeiro VARCHAR(50) NOT NULL,
    versao BIGINT NOT NULL
);

CREATE TABLE recebimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagamento_id BIGINT NOT NULL REFERENCES pagamentos(id),
    valor NUMERIC(10,2) NOT NULL CHECK (valor > 0),
    data DATE NOT NULL,
    metodo VARCHAR(30) NOT NULL,
    sinal BOOLEAN NOT NULL
);

CREATE INDEX idx_recebimentos_pagamento ON recebimentos(pagamento_id);

CREATE TABLE despesas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    categoria VARCHAR(100) NOT NULL,
    valor NUMERIC(10,2) NOT NULL CHECK (valor > 0),
    vencimento DATE NOT NULL,
    data_pagamento DATE,
    metodo VARCHAR(30),
    CHECK ((data_pagamento IS NULL) = (metodo IS NULL))
);
