CREATE TABLE precificacao_execucoes_pid (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competencia DATE NOT NULL REFERENCES precificacao_metas_mensais(competencia),
    data_apuracao DATE NOT NULL,
    delta_dias BIGINT NOT NULL CHECK (delta_dias > 0),
    valor_meta NUMERIC(12, 2) NOT NULL CHECK (valor_meta > 0),
    resultado_realizado NUMERIC(12, 2) NOT NULL,
    referencia_acumulada NUMERIC(12, 2) NOT NULL,
    erro_normalizado DOUBLE PRECISION NOT NULL,
    termo_proporcional DOUBLE PRECISION NOT NULL,
    termo_integral DOUBLE PRECISION NOT NULL,
    termo_derivativo DOUBLE PRECISION NOT NULL,
    saida_bruta DOUBLE PRECISION NOT NULL,
    ajuste_limitado DOUBLE PRECISION NOT NULL,
    integral_acumulada DOUBLE PRECISION NOT NULL,
    ganho_proporcional DOUBLE PRECISION NOT NULL,
    ganho_integral DOUBLE PRECISION NOT NULL,
    ganho_derivativo DOUBLE PRECISION NOT NULL,
    ajuste_minimo DOUBLE PRECISION NOT NULL,
    ajuste_maximo DOUBLE PRECISION NOT NULL,
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    CONSTRAINT uk_precificacao_execucao_dia UNIQUE (competencia, data_apuracao),
    CHECK (EXTRACT(DAY FROM competencia) = 1),
    CHECK (date_trunc('month', data_apuracao)::date = competencia),
    CHECK (ajuste_minimo < ajuste_maximo)
);
