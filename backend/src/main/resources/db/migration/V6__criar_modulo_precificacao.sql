CREATE TABLE precificacao_metas_mensais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competencia DATE NOT NULL,
    valor_meta NUMERIC(12, 2) NOT NULL CHECK (valor_meta > 0),
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    CONSTRAINT uk_precificacao_meta_competencia UNIQUE (competencia),
    CHECK (EXTRACT(DAY FROM competencia) = 1)
);

CREATE TABLE precificacao_politica (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    ganho_proporcional DOUBLE PRECISION NOT NULL,
    ganho_integral DOUBLE PRECISION NOT NULL,
    ganho_derivativo DOUBLE PRECISION NOT NULL,
    ajuste_minimo DOUBLE PRECISION NOT NULL,
    ajuste_maximo DOUBLE PRECISION NOT NULL,
    desconto_fidelidade NUMERIC(5, 4),
    quantidade_os_fidelidade INTEGER,
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    atualizada_em TIMESTAMP NOT NULL,
    CHECK (ajuste_minimo < ajuste_maximo),
    CHECK ((desconto_fidelidade IS NULL AND quantidade_os_fidelidade IS NULL)
        OR (desconto_fidelidade >= 0 AND desconto_fidelidade < 1 AND quantidade_os_fidelidade >= 1))
);

CREATE TABLE precificacao_execucoes_pid (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competencia DATE NOT NULL REFERENCES precificacao_metas_mensais(competencia),
    data_apuracao DATE NOT NULL,
    delta_dias BIGINT NOT NULL CHECK (delta_dias > 0),
    valor_meta NUMERIC(12, 2) NOT NULL CHECK (valor_meta > 0),
    resultado_realizado NUMERIC(12, 2) NOT NULL,
    referencia_acumulada NUMERIC(12, 2) NOT NULL,
    erro_normalizado DOUBLE PRECISION NOT NULL,
    termo_proporcional DOUBLE PRECISION NOT NULL,
    termo_integral DOUBLE PRECISION NOT NULL,
    termo_derivativo DOUBLE PRECISION NOT NULL,
    saida_bruta DOUBLE PRECISION NOT NULL,
    ajuste_limitado DOUBLE PRECISION NOT NULL,
    integral_acumulada DOUBLE PRECISION NOT NULL,
    ganho_proporcional DOUBLE PRECISION NOT NULL,
    ganho_integral DOUBLE PRECISION NOT NULL,
    ganho_derivativo DOUBLE PRECISION NOT NULL,
    ajuste_minimo DOUBLE PRECISION NOT NULL,
    ajuste_maximo DOUBLE PRECISION NOT NULL,
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    CONSTRAINT uk_precificacao_execucao_dia UNIQUE (competencia, data_apuracao),
    CHECK (date_trunc('month', data_apuracao)::date = competencia),
    CHECK (ajuste_minimo < ajuste_maximo)
);

CREATE TABLE precificacao_sugestoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id UUID NOT NULL REFERENCES ordens_servico(id),
    cliente_id UUID NOT NULL REFERENCES clientes(id),
    execucao_pid_id BIGINT REFERENCES precificacao_execucoes_pid(id),
    preco_base NUMERIC(12, 2) NOT NULL CHECK (preco_base > 0),
    ajuste_pid DOUBLE PRECISION NOT NULL,
    preco_ajustado NUMERIC(12, 2) NOT NULL CHECK (preco_ajustado > 0),
    desconto_fidelidade NUMERIC(5, 4) NOT NULL CHECK (desconto_fidelidade >= 0 AND desconto_fidelidade < 1),
    preco_apos_fidelidade NUMERIC(12, 2) NOT NULL CHECK (preco_apos_fidelidade > 0),
    piso_minimo NUMERIC(12, 2) NOT NULL CHECK (piso_minimo > 0),
    preco_sugerido NUMERIC(12, 2) NOT NULL CHECK (preco_sugerido > 0),
    ordens_concluidas INTEGER NOT NULL CHECK (ordens_concluidas >= 0),
    ordens_canceladas INTEGER NOT NULL CHECK (ordens_canceladas >= 0),
    elegivel_fidelidade BOOLEAN NOT NULL,
    justificativa VARCHAR(2000) NOT NULL,
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aprovada_por_id BIGINT REFERENCES usuarios(id),
    aprovada_em TIMESTAMP,
    CHECK ((aprovada_por_id IS NULL) = (aprovada_em IS NULL))
);

CREATE INDEX idx_precificacao_sugestoes_os ON precificacao_sugestoes(ordem_servico_id, criada_em DESC);
