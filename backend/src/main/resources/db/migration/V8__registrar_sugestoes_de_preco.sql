CREATE TABLE precificacao_sugestoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id UUID NOT NULL REFERENCES ordens_servico(id),
    cliente_id UUID NOT NULL REFERENCES clientes(id),
    execucao_pid_id BIGINT REFERENCES precificacao_execucoes_pid(id),
    preco_base NUMERIC(12, 2) NOT NULL CHECK (preco_base > 0),
    ajuste_pid DOUBLE PRECISION NOT NULL,
    preco_ajustado NUMERIC(12, 2) NOT NULL CHECK (preco_ajustado > 0),
    desconto_fidelidade NUMERIC(5, 4) NOT NULL CHECK (desconto_fidelidade >= 0 AND desconto_fidelidade < 1),
    preco_apos_fidelidade NUMERIC(12, 2) NOT NULL CHECK (preco_apos_fidelidade > 0),
    piso_minimo NUMERIC(12, 2) NOT NULL CHECK (piso_minimo > 0),
    preco_sugerido NUMERIC(12, 2) NOT NULL CHECK (preco_sugerido > 0),
    ordens_concluidas INTEGER NOT NULL CHECK (ordens_concluidas >= 0),
    ordens_canceladas INTEGER NOT NULL CHECK (ordens_canceladas >= 0),
    elegivel_fidelidade BOOLEAN NOT NULL,
    justificativa VARCHAR(2000) NOT NULL,
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_precificacao_sugestoes_os ON precificacao_sugestoes(ordem_servico_id, criada_em DESC);
