CREATE TABLE precificacao_metas_mensais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competencia DATE NOT NULL UNIQUE,
    valor_meta NUMERIC(12, 2) NOT NULL CHECK (valor_meta > 0),
    indicador VARCHAR(40) NOT NULL CHECK (indicador = 'RESULTADO_DE_CAIXA'),
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    CHECK (EXTRACT(DAY FROM competencia) = 1)
);

CREATE TABLE precificacao_estados_pid (
    competencia DATE PRIMARY KEY REFERENCES precificacao_metas_mensais(competencia) ON DELETE CASCADE,
    integral_acumulada DOUBLE PRECISION NOT NULL DEFAULT 0,
    erro_anterior DOUBLE PRECISION,
    ultima_atualizacao DATE,
    CHECK (EXTRACT(DAY FROM competencia) = 1),
    CHECK (ultima_atualizacao IS NULL OR date_trunc('month', ultima_atualizacao)::date = competencia)
);

CREATE TABLE precificacao_politica (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    ganho_proporcional DOUBLE PRECISION NOT NULL,
    ganho_integral DOUBLE PRECISION NOT NULL,
    ganho_derivativo DOUBLE PRECISION NOT NULL,
    ajuste_minimo DOUBLE PRECISION NOT NULL,
    ajuste_maximo DOUBLE PRECISION NOT NULL,
    desconto_fidelidade NUMERIC(5, 4),
    quantidade_os_fidelidade INTEGER,
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    atualizada_em TIMESTAMP NOT NULL,
    CHECK (ajuste_minimo < ajuste_maximo),
    CHECK ((desconto_fidelidade IS NULL AND quantidade_os_fidelidade IS NULL)
        OR (desconto_fidelidade >= 0 AND desconto_fidelidade < 1 AND quantidade_os_fidelidade >= 1))
);
