CREATE TABLE precificacao_aprovacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id UUID NOT NULL REFERENCES ordens_servico(id),
    sugestao_id BIGINT NOT NULL UNIQUE REFERENCES precificacao_sugestoes(id),
    valor_anterior NUMERIC(12, 2) NOT NULL CHECK (valor_anterior > 0),
    valor_aprovado NUMERIC(12, 2) NOT NULL CHECK (valor_aprovado > 0),
    valor_recebido NUMERIC(12, 2) NOT NULL CHECK (valor_recebido >= 0),
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    aprovada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_precificacao_aprovacoes_os ON precificacao_aprovacoes(ordem_servico_id, aprovada_em DESC);
